// A keyed script must actually run.
//
// THE BUG
//
//     "Wrong Special Key, or the delivery was tampered with"
//
// the moment a licence was generated from the Users tab and the script was run.
//
// SHK MEANS "CIPHERTEXT FOLLOWS". The bootstrap reads that header and runs
//
//     local K = getgenv().ScripterHubKey        -- the LICENCE key
//     src = DEC(K)                              -- decrypt with it
//     if not src then DIE("Wrong Special Key...")
//
// but the worker was serving the PLAIN artifact under that header. Plaintext
// decrypted with a key that was never applied to it produces garbage, the SHOK
// magic check fails, and the script dies with a message that reads like a
// supply-chain attack rather than a header/format mismatch.
//
// No keyed script has ever run. Keyless ones work because SHX carries plain Lua
// and the bootstrap skips DEC entirely.
//
// WHAT IS ASSERTED
//
// Not "the cipher looks symmetric" - three real agreements:
//
//   1. the worker's encryptor and the SHIPPED sh-crypto.js produce identical
//      ciphertext for the same key and text,
//   2. sh-crypto.js decrypts the worker's ciphertext back to the exact artifact
//      (so the cipher really is its own inverse), and a different key opens
//      nothing,
//   3. the SHIPPED LUA seed agrees with the JavaScript seed for all four state
//      words, because the Lua is what actually runs in the executor. If those
//      two disagree by one unit, every keyed script fails again - and a test
//      that only ever exercised JS could not see it.
//
// Run: node tools/keyed_delivery_test.mjs

import fs from 'node:fs';
import fengari from 'fengari';
import {
    shEncryptPayload,
    shDecryptPayload,
    shSeed as clientSeed,
    xs128Next as clientXs,
} from '../sh-crypto.js';

const workerSrc = fs.readFileSync(new URL('../For Cloudflare/worker.js', import.meta.url), 'utf8');

let pass = 0, fail = 0;
function check(name, cond, detail = '') {
    if (cond) { console.log('  ok   ' + name); pass++; }
    else { console.log('  FAIL ' + name + (detail ? ' - ' + detail : '')); fail++; }
}

console.log('[KD] a keyed script can decrypt its own delivery');
console.log('-'.repeat(72));

// ---------------------------------------------------------------- the worker's
console.log('');
console.log("the worker's encryptor is the shipped cipher");

function lift(re) { const m = workerSrc.match(re); return m ? m[0] : null; }
const seedJs = lift(/function shSeed\(key, idx\) \{[\s\S]*?\n\}/);
const xsJs = lift(/function xs128Next\(s\) \{[\s\S]*?\n\}/);
const encJs = lift(/function shEncryptForLoader\(text, key\) \{[\s\S]*?\n\}/);
check('the worker can encrypt for the loader', !!(seedJs && xsJs && encJs));

let workerSeed = null, workerEncrypt = null;
if (seedJs && xsJs && encJs) {
    // `new Function` runs in global scope, so a parameter named TextEncoder
    // SHADOWS the global and the lifted body receives the parameter. It must
    // therefore be handed the real constructor, not a stand-in.
    const api = new Function(
        'TextEncoder', 'btoa',
        seedJs + '\n' + xsJs + '\n' + encJs + '\nreturn { shSeed, xs128Next, shEncryptForLoader };'
    )(globalThis.TextEncoder, s => Buffer.from(s, 'binary').toString('base64'));
    workerSeed = api.shSeed;
    workerEncrypt = api.shEncryptForLoader;

    // 1. same keystream as the shipped sh-crypto.js
    const KEYS = ['A7xK-9pQ2.mR~tZ1', 'another-key', 'x', '', 'a-very-long-licence-key-000000000000000'];
    const seedMismatch = [];
    for (const k of KEYS) {
        for (let i = 0; i < 4; i++) {
            if (workerSeed(k, i) !== clientSeed(k, i)) seedMismatch.push(k + '#' + i);
        }
    }
    check('the seed matches sh-crypto.js for every key and word', seedMismatch.length === 0,
        seedMismatch.slice(0, 4).join(', '));

    // The keystream itself, not just the seeds: two xorshift states can start
    // identical and diverge on the first step if a shift differs by one bit.
    const xsMismatch = [];
    for (const k of KEYS) {
        const mine = [0, 1, 2, 3].map(i => workerSeed(k, i));
        const theirs = [0, 1, 2, 3].map(i => clientSeed(k, i));
        for (let i = 0; i < 64; i++) {
            if (api.xs128Next(mine) !== clientXs(theirs)) { xsMismatch.push(k + ' step ' + i); break; }
        }
    }
    check('the keystream matches sh-crypto.js over 64 steps', xsMismatch.length === 0,
        xsMismatch.slice(0, 3).join(', '));

    const ARTIFACT = '-- generated by ScripterHub\nlocal function boot()\n  print("hello")\nend\nboot()\nreturn {"a","b"}\n';
    const LICENCE = 'A7xK-9pQ2.mR~tZ1';

    // 1b. byte-identical ciphertext, which subsumes the keystream comparison
    const sameBody = KEYS.every(k => workerEncrypt(ARTIFACT, k) === shEncryptPayload(ARTIFACT, k));
    check('the ciphertext is byte-identical to shEncryptPayload', sameBody,
        'the loader would decrypt the worker output differently from the browser');

    // 2. it really is its own inverse, and a wrong key really opens nothing
    const cipher = workerEncrypt(ARTIFACT, LICENCE);
    check('the worker produced a ciphertext body', typeof cipher === 'string' && cipher.length > 0);
    check('it decrypts back to the exact artifact', shDecryptPayload(cipher, LICENCE) === ARTIFACT);
    check('a different licence opens nothing', shDecryptPayload(cipher, 'other-key-entirely') === null,
        'the wrong key still produced readable output');
}

// ------------------------------------------------------------------ the Lua
//
// DEC() IS NOT EXERCISED HERE, AND THAT IS DELIBERATE.
//
// It reads the delivered body from the enclosing scope, exactly as the
// bootstrap does - B is a closure variable, not an argument - so calling
// DEC(cipher) in isolation decrypts an absent B and "fails" for reasons that
// have nothing to do with the cipher. That is how this test first reported a
// JS/Lua mismatch that did not exist: the seeds matched exactly.
//
// SD IS EXERCISED. It is self-contained, and it is the only place the two
// implementations can diverge in a way that is not a literal transcription:
// shSeed walks UTF-8 bytes with `h*33 + b` mod 2^32 in JavaScript doubles,
// while SD does the same in Lua. One unit of disagreement shifts the entire
// keystream and every keyed script fails the SHOK magic again.
console.log('');
console.log('the shipped Lua agrees with the JavaScript');

const LUA = fengari.lua, AUX = fengari.lauxlib;

function luaDecryptBlock() {
    const from = workerSrc.indexOf('// ---- 5. decrypt locally with the Special Key');
    const to = workerSrc.indexOf('local LS=loadstring or load', from);
    if (from < 0 || to < 0) return '';
    const seg = workerSrc.slice(from, to);
    const pieces = [];
    const re = /^\s*\+ '(.*)'\s*,?\s*$/gm;
    let m;
    while ((m = re.exec(seg)) !== null) pieces.push(m[1]);
    return pieces
        .map(p => p.replace(/%%/g, '%').replace(/\\n/g, '\n').replace(/\\"/g, '"').replace(/\\\\/g, '\\'))
        .join('\n');
}

{
    const block = luaDecryptBlock();
    check('the loader DEC() is present', ['BX', 'SD', 'NX', 'DEC']
        .every(n => block.indexOf('local function ' + n + '(') !== -1));

    const LUA_KEY = 'A7xK-9pQ2.mR~tZ1';
    // SLICE SD OUT BY ITS NEIGHBOURS. Its third line ends with `end` (it
    // closes the inner `for`) while the function itself continues, so any
    // "stop at the first end" heuristic truncates it and drops `return h` -
    // which then reads as a key mismatch rather than a broken extraction.
    const sd = block.slice(block.indexOf('local function SD('), block.indexOf('local function NX('));
    check('SD was extracted whole', sd.indexOf('return h') !== -1,
        'the seed function lost its return statement');

    if (sd.indexOf('return h') !== -1 && workerSeed) {
        // %.0f, NOT %d.
//
// These are 32-bit UNSIGNED values above 2^31, held as Lua doubles. Real Lua
// prints them with %d via its own integer path; fengari raises "number has no
// integer representation" instead. %.0f asks for no decimal places, which is
// the same digits either way - and it cannot silently round a seed, because
// the comparison against the JavaScript is exact.
        const probe = sd + '\nlocal o={}\nfor i=0,3 do o[#o+1]=string.format("%.0f",SD('
            + JSON.stringify(LUA_KEY) + ',i)) end\nreturn table.concat(o,",")';
        const st = AUX.luaL_newstate();
        fengari.lualib.luaL_openlibs(st);
        let okRun = false, luaSeeds = [], why = '';
        const lrc = AUX.luaL_loadbuffer(st, fengari.to_luastring(probe), null, fengari.to_luastring('@sd'));
        if (lrc !== 0) why = 'load: ' + String(LUA.lua_tojsstring(st, -1)).slice(0, 160);
        else if (LUA.lua_pcall(st, 0, 1, 0) !== 0) why = 'run: ' + String(LUA.lua_tojsstring(st, -1)).slice(0, 160);
        else {
            luaSeeds = String(LUA.lua_tojsstring(st, -1)).split(',').map(Number);
            okRun = luaSeeds.length === 4;
            if (!okRun) why = 'returned: ' + String(LUA.lua_tojsstring(st, -1)).slice(0, 160);
        }
        const jsSeeds = [0, 1, 2, 3].map(i => workerSeed(LUA_KEY, i));
        check('the shipped Lua seed matches the JavaScript, all four words',
            okRun && luaSeeds.every((v, i) => v === jsSeeds[i]),
            okRun ? 'lua=' + JSON.stringify(luaSeeds) + ' js=' + JSON.stringify(jsSeeds) : (why || 'the Lua probe did not run'));
    }

    check('the loader reports a failed magic', /Wrong Special Key/.test(workerSrc),
        'the loader no longer says which check failed');
}

// ------------------------------------------------------------------- wiring
console.log('');
console.log('the delivery actually encrypts for keyed scripts');
check('SHK is still used for a keyed script', /out = 'SHK\\n'/.test(workerSrc));
check('SHX keeps carrying plain Lua for a keyless one',
    /out = keyLine \? \('SHX\\n' \+ keyLine \+ '\\n'\) : 'SHL\\n';\s*\n\s*out \+= inlineBlob;/.test(workerSrc),
    'the keyless branch must NOT be encrypted - it has no licence to encrypt with');
check('the keyed body is encrypted with the session licence key',
    /shEncryptForLoader\(inlineBlob, licKey\)/.test(workerSrc),
    'SHK still carries plaintext, which is the reported bug');
check('the licence key comes from the validated session row',
    /sessionLicenseKey = row && row\.license_key \? String\(row\.license_key\) : '';/.test(workerSrc),
    'it must be the key the gate actually checked, not a supplied one');
check('and the block that reads the row is hoisted out of its scope',
    /let sessionLicenseKey = '';/.test(workerSrc),
    'reading `row` from the delivery code throws "row is not defined" on every keyed delivery');
check('a keyed delivery with no licence is refused rather than sent plain',
    /if \(!licKey\) \{\s*\n\s*return refuse\(DENY\.NEEDS_KEY\)/.test(workerSrc));

console.log('');
console.log('KEYED DELIVERY   ' + pass + ' passed, ' + fail + ' failed');
process.exit(fail ? 1 : 0);