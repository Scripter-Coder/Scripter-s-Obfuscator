console.log('[H3] the INJECTED key unlocks the payload, with no HTTP at all...');
// This is the real test. The bootstrap sets the global and the baked chunk
// must use it. Any HTTP attempt is a hard failure, recorded, so a fallback
// that silently fires cannot masquerade as success.
async function runBuild(code, opts = {}) {
  const L = lauxlib.luaL_newstate();
  lualib.luaL_openlibs(L);
  const httpHits = [];
  lauxlib.luaL_dostring(L, to_luastring([
    'getgenv = function() return _G end',
    'HANDOFF_HTTP = 0',
    // A checksum computed IN LUA, because a wrong key yields a payload that
    // is not valid UTF-8 and shuttling it across the C boundary throws. The
    // comparison we care about is "same payload as the real key?" and that is
    // answerable from a rolling sum.
    'HANDOFF_SUM = -1',
    'loadstring = function(s)',
    '  local h = 5381',
    '  for i = 1, #s do h = (h * 33 + string.byte(s, i)) % 4294967296 end',
    '  HANDOFF_SUM = h',
    '  HANDOFF_LEN = #s',
    '  HANDOFF_RUN = s',
    '  return function() end',
    'end',
    'game = { GetService = function() return { SetCore = function() end } end }',
    'warn = function() end'
  ].join('\n')));
  // game.HttpGet records and returns a plausible failure, so if the fallback
  // runs we can see it.
  lauxlib.luaL_dostring(L, to_luastring(
    'game.HttpGet = function(self, u) HANDOFF_HTTP = HANDOFF_HTTP + 1; return nil end'
  ));
  if (opts.injectKey !== null) {
    lauxlib.luaL_dostring(L, to_luastring('getgenv().__SH_SPLITKEY = ' + JSON.stringify(opts.injectKey === undefined ? opts.keyline : opts.injectKey)));
  }
  if (opts.license) {
    lauxlib.luaL_dostring(L, to_luastring('getgenv().ScripterHubKey = ' + JSON.stringify(opts.license)));
  }
  const st = lauxlib.luaL_dostring(L, to_luastring(code));
  const readNum = (n) => { lua.lua_getglobal(L, to_luastring(n)); const v = Number(lua.lua_tonumber(L, -1)); lua.lua_pop(L, 1); return v; };
  // readStr is only safe for ASCII-ish globals. HANDOFF_RUN may be arbitrary
  // bytes, so callers that only need "did something run" use `sum`/`len`.
  const readStr = (n) => { lua.lua_getglobal(L, to_luastring(n)); const p = lua.lua_tostring(L, -1); const v = p ? to_jsstring(p) : null; lua.lua_pop(L, 1); return v; };
  return {
    st,
    http: readNum('HANDOFF_HTTP'),
    sum: readNum('HANDOFF_SUM'),
    len: readNum('HANDOFF_LEN'),
    ran: (() => {
      lua.lua_getglobal(L, to_luastring('HANDOFF_RUN'));
      const has = !lua.lua_isnil(L, -1);
      lua.lua_pop(L, 1);
      return has;
    })(),
    verdict: readStr('__SH_SERVER_VERDICT')
  };
}
{
  const r = await runBuild(keylessB.code, { keyline: keylessB.keyline });
  check('free build: executes cleanly', () => {
    assert.strictEqual(r.st, lua.LUA_OK, 'the build did not run cleanly');
    return true;
  });
  check('free build: makes ZERO HTTP requests', () => {
    assert.strictEqual(r.http, 0, 'it fell back to HTTP ' + r.http + ' time(s) - the handoff did not take');
    return true;
  });
  check('free build: the payload is handed to loadstring', () => {
    assert.ok(r.ran, 'no payload reached loadstring, so the VM never unlocked');
    assert.ok(r.len > 0, 'the payload was empty');
    return true;
  });
  check('free build: the handed-over payload is substantial', () => {
    // Not "contains the marker": by this point the source is inside the VM
    // blob, so a substring check would be meaningless. What matters is that
    // something real was produced.
    assert.ok(r.len > 100, 'payload was only ' + r.len + ' bytes');
    return true;
  });
}
{
  const r = await runBuild(authB.code, { keyline: authB.keyline, license: 'LIC-KEY' });
  check('Require Key build: executes cleanly', () => {
    assert.strictEqual(r.st, lua.LUA_OK, 'the build did not run cleanly');
    return true;
  });
  check('Require Key build: makes ZERO HTTP requests', () => {
    assert.strictEqual(r.http, 0, 'it fell back to HTTP ' + r.http + ' time(s) - the handoff did not take');
    return true;
  });
  check('Require Key build: the payload is handed to loadstring', () => {
    assert.ok(r.ran, 'no payload reached loadstring');
    assert.ok(r.len > 0, 'the payload was empty');
    return true;
  });
  check('Require Key build: the server verdict global is populated', () => {
    // The payload's own API layer reads this. Without it the script would
    // consider itself unauthorised even though the gate approved the run.
    assert.strictEqual(r.verdict, 'Valid', 'verdict was ' + JSON.stringify(r.verdict));
    return true;
  });
}

// ---------------------------------------------------------------------------
console.log('[H4] a FORGED injection is still rejected...');
// The security property that matters most. A caller who sets the global
// themselves must learn nothing, because t0 and chk are baked into the file
// and the padded key bytes are not.
{
  // THE REFERENCE. Everything in H4 is "did this differ from the real key?"
  const good = await runBuild(keylessB.code, { keyline: keylessB.keyline });
  check('the correct key produces a payload', () => {
    assert.ok(good.ran, 'the real key did not unlock the payload');
    assert.ok(good.len > 0, 'payload length was zero');
    return true;
  });
  const goodSum = good.sum;

  await check('a wrong t0 does not unlock the payload', async () => {
    const forged = (keylessB.t0 + 1) + ' ' + keylessB.chk + ' ' + keylessB.padded.join(' ');
    const r = await runBuild(keylessB.code, { injectKey: forged });
    assert.ok(!r.ran, 'a forged t0 unlocked the payload');
    return true;
  });
  await check('a wrong chk does not unlock the payload', async () => {
    const forged = keylessB.t0 + ' ' + (keylessB.chk + 1) + ' ' + keylessB.padded.join(' ');
    const r = await runBuild(keylessB.code, { injectKey: forged });
    assert.ok(!r.ran, 'a forged chk unlocked the payload');
    return true;
  });
  await check('the right t0/chk with the WRONG key bytes yields a DIFFERENT payload', async () => {
    // THIS IS THE REAL ATTACK, and note what it is NOT.
    //
    // t0 and chk are readable in the file, so those two checks are not the
    // protection — the padded bytes are what an attacker does not have. So the
    // assertion cannot be "nothing runs": the VM starts with a wrong seed and
    // happily emits garbage. The assertion is that the garbage is NOT the
    // script. Anything that produced the same payload would mean the key
    // bytes are not actually load-bearing.
    const forged = keylessB.t0 + ' ' + keylessB.chk + ' ' + keylessB.padded.map(n => (n + 1) % 256).join(' ');
    const r = await runBuild(keylessB.code, { injectKey: forged });
    assert.notStrictEqual(r.sum, goodSum, 'wrong key bytes produced the SAME payload as the real key');
    return true;
  });
  await check('a truncated key line does not unlock the payload', async () => {
    const r = await runBuild(keylessB.code, { injectKey: keylessB.t0 + ' ' + keylessB.chk });
    assert.ok(!r.ran, 'a truncated key unlocked the payload');
    return true;
  });
  await check('no injection at all does not unlock the payload', async () => {
    // This is the migration case: an old bootstrap, or a file published
    // before Phase 3. There is no key, so nothing may run.
    const r = await runBuild(keylessB.code, { injectKey: null });
    assert.ok(!r.ran, 'the payload ran with no key at all');
    return true;
  });
  await check('an empty injection is treated as absent', async () => {
    const r = await runBuild(keylessB.code, { injectKey: '' });
    assert.ok(!r.ran, 'an empty string was accepted as a key');
    return true;
  });
  await check('a non-string injection is treated as absent', async () => {
    const r = await runBuild(keylessB.code, { injectKey: 12345 });
    assert.ok(!r.ran, 'a number was accepted as a key');
    return true;
  });
}

// ---------------------------------------------------------------------------
console.log('[H5] the legacy HTTP path still exists for already-published files...');
{
  await check('with no injection, a Require Key build reaches for /sh/auth', async () => {
    // It must TRY. If it silently gave up instead, every file published
    // before this change would break on upgrade — the outage the /sh/k
    // compatibility window exists to prevent.
    const r = await runBuild(authB.code, { injectKey: null, license: 'LIC-KEY' });
    assert.ok(r.http > 0, 'the legacy path never fired; old files would break');
    return true;
  });
  await check('with no injection, a free build reaches for /sh/k', async () => {
    const r = await runBuild(keylessB.code, { injectKey: null });
    assert.ok(r.http > 0, 'the legacy path never fired for the free build');
    return true;
  });
}

