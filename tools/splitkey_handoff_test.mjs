// =============================================================================
// SPLIT-KEY HANDOFF — the contract between the worker and the obfuscator
// =============================================================================
// Two separately-bundled programs have to agree on one genv slot name:
//   * the WORKER writes the split key into it  (For Cloudflare/worker.js)
//   * the OBFUSCATOR's baked chunk reads it     (custom-obfuscator.js)
//
// The worker runs on Cloudflare's edge and the obfuscator runs in the owner's
// browser, so there is no shared module graph. The name is therefore written
// twice, and this file is what stops the two copies drifting.
//
// WHY THIS NEEDS A TEST RATHER THAN A COMMENT
// If they drift, nothing throws. The bootstrap writes a key nobody reads, the
// baked chunk silently falls back to its HTTP path, and the /sh/k
// compatibility window quietly becomes load-bearing again — the exact
// regression the handoff exists to remove. The symptom is not a crash; it is
// a security property that stopped being true while every test stayed green.
// A comment saying "keep these in sync" is a request, not a mechanism.
//
// Run:  node tools/splitkey_handoff_test.mjs
// =============================================================================

import assert from 'assert';
import fs from 'node:fs';
import fengari from 'fengari';
import luaparse from 'luaparse';
import { applyCustomObfuscator } from '../custom-obfuscator.js';

const { lauxlib, lualib, lua, to_luastring, to_jsstring } = fengari;

let pass = 0, fail = 0;
const problems = [];
function ok(name) { pass++; console.log('  OK   ' + name); }
function bad(name, why) { fail++; problems.push(name + ': ' + why); console.log('  FAIL ' + name + '\n         ' + why); }
async function check(name, fn) {
  try { const r = await fn(); if (r === false) bad(name, 'returned false'); else ok(name); }
  catch (e) { bad(name, (e && e.message) || String(e)); }
}

// ---------------------------------------------------------------------------
console.log('[H1] the two halves declare the SAME genv slot...');
{
  const workerSrc = fs.readFileSync(new URL('../For Cloudflare/worker.js', import.meta.url), 'utf8');
  const obfSrc = fs.readFileSync(new URL('../custom-obfuscator.js', import.meta.url), 'utf8');

  const grab = (src, file) => {
    const m = src.match(/const\s+SPLITKEY_GENV\s*=\s*'([^']+)'/);
    if (!m) return { file: file, err: 'no SPLITKEY_GENV constant found' };
    return { file: file, value: m[1] };
  };
  const w = grab(workerSrc, 'worker.js');
  const o = grab(obfSrc, 'custom-obfuscator.js');

  check('both halves declare SPLITKEY_GENV', () => {
    assert.ok(!w.err, w.err + ' in worker.js');
    assert.ok(!o.err, o.err + ' in custom-obfuscator.js');
    return true;
  });
  check('the two declarations are IDENTICAL', () => {
    // If these ever differ, the handoff silently stops working and the
    // /sh/k window becomes load-bearing again with no error anywhere.
    assert.strictEqual(w.value, o.value,
      `worker.js has "${w.value}" but custom-obfuscator.js has "${o.value}"`);
    assert.ok(/^__[A-Z_]+$/.test(w.value), 'the slot name should look like a reserved global: ' + w.value);
    return true;
  });
  check('the worker injects it into the Lua bootstrap', () => {
    // The worker's bootstrap builds the assignment from the constant rather
    // than hardcoding the name, so assert on THAT, not on a literal that will
    // never appear in the source.
    assert.ok(/G\[' \+ JSON\.stringify\(SPLITKEY_GENV\) \+ '\]=SK/.test(workerSrc),
      'the bootstrap never writes the split key into the slot');
    return true;
  });
  check('the baked chunk reads it back', () => {
    assert.ok(obfSrc.includes('rawget((getgenv and getgenv())'),
      'the baked chunk no longer reads the slot');
    return true;
  });
  check('the baked chunk still has an HTTP fallback', () => {
    // Without the fallback, every already-published file would break the
    // moment the obfuscator shipped. That is the outage the compat window
    // was invented to prevent, and it must not be repeated.
    assert.ok(obfSrc.includes("options.splitKey.url.replace(/\\/sh\\/k$/, '/sh/auth')"),
      'the legacy /sh/auth path is gone - already-published files would break');
    return true;
  });
}

// ---------------------------------------------------------------------------
console.log('[H2] a fresh obfuscated build prefers the injected key...');
const SRC = 'HANDOFFMARKER = "RAN"\nprint("payload body")\n';

// THE KEY VALUES ARE GENERATED BY THE OBFUSCATOR, not supplied.
//
// An earlier version of this test passed its own t0/chk/paddedKey in the
// options and then asserted the file accepted them. They were silently
// overwritten at custom-obfuscator.js:801-803, so the "keyless unlock"
// assertion was really testing a wrong key against a build that had already
// refused it — a test that could never pass and was only kept alive by the
// assertions around it.
//
// So: build first, then READ BACK what was generated. Those are the exact
// bytes the worker will be told to store, so this is also the honest input to
// the handoff simulation.
function build(opts) {
  const options = Object.assign({
    intensity: 1,
    antiTamper: true, antiSkid: false, antiLogger: false,
    serverKey: { keyUrl: 'https://audit.workers.dev/sh/k', scriptRef: 'ScripterHub0000000099' }
  }, opts);
  const dbg = {};
  const code = applyCustomObfuscator(SRC, options, dbg);
  const sk = options.splitKey || {};
  return {
    code,
    keyline: [sk.t0, sk.chk].concat(sk.paddedKey || []).join(' '),
    t0: sk.t0, chk: sk.chk, padded: sk.paddedKey || [],
    authMode: !!(sk.auth)
  };
}

let authB = null, keylessB = null;
{
  // Require Key ON: keyGate present -> the baked chunk is in auth mode and
  // expects a license before it will do anything.
  authB = build({ keyGate: { keys: [{ key: 'LIC-KEY', expires: Date.now() + 86400000 }] } });
  // Require Key OFF: no keyGate at all, so splitContainer.auth is false.
  keylessB = build({ keyGate: null });

  check('the Require Key build really is in auth mode', () => {
    assert.ok(authB.authMode, 'expected the baked chunk to be in auth mode');
    return true;
  });
  check('the free build really is NOT in auth mode', () => {
    // This assertion is the reason the earlier version of this test was
    // meaningless: both builds were auth mode, so the "keyless" case was
    // never actually exercised.
    assert.ok(!keylessB.authMode, 'the free build was also in auth mode');
    return true;
  });
  check('the obfuscator generated a real split key', () => {
    assert.ok(authB.t0 > 0, 'no t0 was generated');
    assert.ok(authB.chk > 0, 'no chk was generated');
    assert.ok(authB.padded.length >= 3, 'paddedKey is too short: ' + authB.padded.length);
    return true;
  });
  check('both builds are valid Lua', () => {
    assert.doesNotThrow(() => luaparse.parse(authB.code));
    assert.doesNotThrow(() => luaparse.parse(keylessB.code));
    return true;
  });
  check('neither build contains the padded key bytes', () => {
    const joined = authB.padded.join(',');
    assert.ok(!authB.code.includes(joined), 'padded key leaked into the auth build');
    assert.ok(!keylessB.code.includes(joined), 'padded key leaked into the free build');
    return true;
  });
  check('neither build bakes in the genv slot name', () => {
    // A literal "__SH_SPLITKEY" is a free hand-drawn target: it tells a reader
    // exactly which global to overwrite before execution.
    assert.ok(!authB.code.includes('__SH_SPLITKEY'), 'the slot name is a plaintext literal in the auth build');
    assert.ok(!keylessB.code.includes('__SH_SPLITKEY'), 'the slot name is a plaintext literal in the free build');
    assert.ok(authB.code.includes('string.char('), 'the slot name is not assembled at runtime');
    return true;
  });
}

